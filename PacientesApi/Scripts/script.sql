
-- Tabela de pacientes
CREATE TABLE PACIENTES (
    PACIENTE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(100) NOT NULL,
    DATA_NASCIMENTO DATE NOT NULL,
    CPF VARCHAR2(11) NOT NULL,

    CONSTRAINT PK_PACIENTES PRIMARY KEY (PACIENTE_ID),
    CONSTRAINT UK_PACIENTES_CPF UNIQUE (CPF)
);

-- Tabela de remédios associados aos pacientes
CREATE TABLE REMEDIOS (
    REMEDIO_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(100) NOT NULL,
    DOSAGEM VARCHAR2(50) NOT NULL,
    FREQUENCIA_USO VARCHAR2(100) NOT NULL,
    PACIENTE_ID NUMBER NOT NULL,

    CONSTRAINT PK_REMEDIOS PRIMARY KEY (REMEDIO_ID),
    CONSTRAINT FK_REMEDIOS_PACIENTES
        FOREIGN KEY (PACIENTE_ID)
        REFERENCES PACIENTES (PACIENTE_ID)
);

-- Índice para consultas por paciente
CREATE INDEX IDX_REMEDIOS_PACIENTE
ON REMEDIOS (PACIENTE_ID);
